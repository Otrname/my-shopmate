# 从这里开始写你的代码 ↓
import json

# 第 1 步：读取数据
with open("data/orders.json", encoding="utf-8") as f:
    orders = json.load(f)


# 第 2 步：定义订单查询函数（防越权校验）
def get_order(order_id, customer_id):
    order_id = order_id.strip()
    if order_id not in orders:
        raise KeyError("订单不存在")

    order = orders[order_id]
    if order["customer_id"] != customer_id:
        raise PermissionError("无权查询他人订单")

    return order


# 第 3 步：主程序
if __name__ == "__main__":
    current_customer = "C1001"
    order_id = input("请输入订单号：")

    try:
        order = get_order(order_id, current_customer)
    except (KeyError, PermissionError):
        print("抱歉，没有找到这个订单，请检查订单号是否正确。")
    else:
        print(f"订单号：{order_id}")
        print(f"状态：{order['status']}")
        for item in order["items"]:
            print(f"商品：{item['name']} × {item['qty']}")
        print(f"金额：{order['total']} {order['currency']}")